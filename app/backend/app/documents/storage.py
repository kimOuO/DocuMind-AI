"""Where uploaded files live on disk.

Files are stored as ``<data_dir>/<owner_id>/<document_id><extension>``. The
names are generated by the server, so nothing a client sends ends up in a path.
"""

import contextlib
import hashlib
import uuid
from dataclasses import dataclass
from pathlib import Path

from fastapi import UploadFile

CHUNK_BYTES = 1024 * 1024


class UploadTooLarge(Exception):
    pass


@dataclass(frozen=True)
class ReceivedFile:
    temp_path: Path
    size: int
    sha256: str


class FileStorage:
    def __init__(self, base_dir: Path) -> None:
        self._base = base_dir

    async def receive(self, upload: UploadFile, max_bytes: int) -> ReceivedFile:
        """Stream an upload to a temporary file, hashing it on the way.

        Stops as soon as the size limit is exceeded, so an oversized upload is
        never fully written to disk.
        """
        self._base.mkdir(parents=True, exist_ok=True)
        temp_path = self._base / f".upload-{uuid.uuid4().hex}"
        digest = hashlib.sha256()
        size = 0
        try:
            with temp_path.open("wb") as handle:
                while chunk := await upload.read(CHUNK_BYTES):
                    size += len(chunk)
                    if size > max_bytes:
                        raise UploadTooLarge
                    digest.update(chunk)
                    handle.write(chunk)
        except BaseException:
            self.discard(temp_path)
            raise
        return ReceivedFile(temp_path=temp_path, size=size, sha256=digest.hexdigest())

    def relative_path(self, owner_id: uuid.UUID, document_id: uuid.UUID, extension: str) -> str:
        return f"{owner_id}/{document_id}{extension}"

    def commit(self, received: ReceivedFile, relative_path: str) -> None:
        """Move a received file to its final place."""
        target = self._base / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        received.temp_path.replace(target)

    def absolute(self, relative_path: str) -> Path:
        return self._base / relative_path

    def discard(self, path: Path) -> None:
        with contextlib.suppress(FileNotFoundError):
            path.unlink()

    def delete(self, relative_path: str) -> None:
        self.discard(self._base / relative_path)
